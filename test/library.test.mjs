import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { Store } from '../src/store.mjs';
import { Library } from '../src/library.mjs';
import { pdfFixture } from './pdf-fixture.mjs';

test('PDF extraction, evidence anchors, agent answers and atomic citations survive reopen', async t => {
  const dir = mkdtempSync(path.join(os.tmpdir(), 'folio-library-'));
  const store = new Store(dir), library = new Library(store);
  t.after(() => store.close());
  const bytes = pdfFixture();
  const paper = await library.importPdf(bytes, { title:'Evidence study', authors:'A. Researcher', year:'2026', citekey:'Evidence2026' });
  assert.equal(paper.page_count, 1); assert.ok(paper.text_available);
  assert.match(library.page(paper.id,1).text, /Evidence from/);
  assert.equal((await library.importPdf(bytes)).duplicate, true);
  assert.equal(library.list('evidence').length, 1);
  assert.equal(library.search(paper.id,'first')[0].page, 1);
  assert.throws(() => library.page(paper.id,2));
  assert.throws(() => library.addNote(paper.id,1,'made up quote','body'), {code:'QUOTE_MISMATCH'});
  const note = library.addNote(paper.id,1,'Evidence from the first page.','Use 100% evidence & verify.');
  const request = library.request(paper.id,1,note.quote,'Explain the evidence.');
  assert.equal(library.requests().length,1);
  library.answer(request.id,'The first page contains a test statement (p.1).','Test agent');
  assert.throws(() => library.answer(request.id,'Overwrite','Other agent'),{code:'REQUEST_CONFLICT'});
  assert.equal(library.requests().length,0);
  const project = store.create('Citation test');
  const args = { paper_id:paper.id,project_id:project.id,expected_revision:1,filename:'main.tex',page:1,note_id:note.id };
  const cited = library.cite(args);
  assert.match(cited.files['main.tex'], /100\\% evidence \\& verify/);
  assert.match(cited.files['main.tex'], /\\cite\[p\.~1\]\{Evidence2026\}/);
  assert.ok(cited.files['main.tex'].indexOf('Source:') < cited.files['main.tex'].indexOf('\\end{document}'));
  assert.match(cited.files['references.bib'], /@misc\{Evidence2026/);
  assert.match(cited.files['main.tex'], /\\bibliography\{references\}/);
  assert.throws(() => library.cite(args),{code:'REVISION_CONFLICT'});
  const again = library.cite({...args,expected_revision:2});
  assert.equal((again.files['references.bib'].match(/@misc/g)||[]).length,1);
  assert.ok(again.files['main.tex'].lastIndexOf('Source:') < again.files['main.tex'].indexOf('\\bibliographystyle'));
  library.update(paper.id,1,{title:'Corrected title'});
  assert.throws(() => library.update(paper.id,1,{title:'stale'}),{code:'REVISION_CONFLICT'});
  assert.throws(() => library.cite({...args,expected_revision:3}),{code:'CITEKEY_CONFLICT'});
  assert.equal(store.get(project.id).revision,3);
  await assert.rejects(library.importPdf(Buffer.from('not a PDF')),{code:'INVALID_RESEARCH_DATA'});
  await assert.rejects(library.importPdf(Buffer.from('%PDF-invalid')),{code:'INVALID_PDF'});
  const other = new Store(dir), reopened = new Library(other);
  assert.equal(reopened.info(paper.id).notes[0].body,note.body);
  assert.equal(reopened.info(paper.id).requests[0].status,'answered');
  assert.deepEqual(reopened.pdf(paper.id),bytes); other.close();
});
